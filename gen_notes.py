#!/usr/bin/env python3
# PSG divider table (true hex), midi 36..84
import math
def freq(m): return 440.0 * 2**((m-69)/12)
rows=[]
for m in range(36,85):
    n = round(3579545/(32*freq(m)))
    rows.append(f"${n:04X}")
out=["; generated by gen_notes.py","note_tbl:"]
for i in range(0,len(rows),8):
    out.append("    DW "+", ".join(rows[i:i+8]))
with open("notes.inc","w") as fh: fh.write("\n".join(out)+"\n")
print("notes.inc ok")
